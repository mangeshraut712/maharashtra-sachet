import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('judge path: home to Metro demo to explanation and Marathi', async ({ page }) => {
  await page.goto('/?demo=1')
  await page.locator('#metroEntry').click()
  await expect(page).toHaveURL(/\/metro\?demo=1/)
  await expect(page.locator('#metroDemoBanner')).toContainText('DEMO / sample data')
  await expect(page.locator('#metroStations button')).toHaveCount(16)
  await expect(page.locator('#metroFeed article')).toHaveCount(1)
  await expect(page.locator('#metroFeed')).toContainText('Marunji water service notice')
  await expect(page.locator('#metroFeed')).not.toContainText('Sindhudurg')
  await expect(page.locator('#metroPrecision')).toContainText('District-alias precision only')
  await page.getByRole('button', { name: 'Ramwadi', exact: true }).click()
  await expect(page.locator('#metroSelection')).toContainText('Ramwadi → Pune district')
  await expect(page.locator('#metroFeed article')).toHaveCount(1)
  await page.getByRole('link', { name: /Explain in plain words/ }).click()
  await expect(page).toHaveURL(/\/explain\?demo=1$/)
  await expect(page.locator('#explainDemoBanner')).toBeVisible()
  await expect(page.locator('#alertText')).toHaveValue(/DEMO \/ SAMPLE DATA/)
  await expect(page.locator('#explainResult')).toBeVisible()
  await expect(page.locator('#fallbackNote')).toContainText('not configured')
  await page.getByRole('button', { name: 'मराठी', exact: true }).click()
  await expect(page.locator('#langBlocks [lang="mr"]')).toBeVisible()
  await expect(page.locator('#langBlocks [lang="en"]')).toBeHidden()
  await expect(page.locator('#langBlocks [lang="mr"]')).toContainText('सूचनेत')
  await expect(page.locator('#explainDemoBanner')).toBeVisible()
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(axe.violations.map(v => v.id)).toEqual([])
})

test('Metro unavailable feed retains demo entry and cannot imply an all-clear', async ({ page }) => {
  await page.route('**/api/meta', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ environment: 'production' }) }))
  await page.route('**/api/alerts?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"Relay unavailable"}' }))
  await page.goto('/metro')
  await expect(page.locator('#metroStatus')).toContainText('Relay unavailable')
  await expect(page.locator('#metroDemoBanner')).toBeHidden()
  await expect(page.locator('#metroDemoLink')).toBeVisible()
  await expect(page.locator('#metroSafety')).toContainText('not an all-clear')
  await expect(page.locator('#metroFeed article')).toHaveCount(0)
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(axe.violations.map(v => v.id)).toEqual([])
})
